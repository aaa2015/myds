#!/usr/bin/env python3
"""CPU mock fullmodel-controller controls with original-layout raw fixtures.

No model/native binary, Metal API, service, or actual process-memory measurement
is invoked. The actual controller reads all generated logits/state/memory files.
"""
import argparse
import copy
import importlib.util
import json
from pathlib import Path
import struct
import tempfile
from types import SimpleNamespace
