def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--out',type=Path,required=True)
    args=p.parse_args();tool=Path(__file__).with_name('run_moe_workspace_fullmodel_window.py')
    spec=importlib.util.spec_from_file_location('moews_fullmodel_controller',tool)
    r=importlib.util.module_from_spec(spec);spec.loader.exec_module(r)
    bs=importlib.util.spec_from_file_location('cpu_raw_hashes',tool.with_name('review_moe_workspace_fullmodel_artifacts.py'))
    base=importlib.util.module_from_spec(bs);bs.loader.exec_module(base);hashes=base.ByteHashes()
    repo=tool.parent.parent;realplan=repo/'docs/benchmarks/2026-10-24-moe-workspace/experiment-plan-v2.json'
    checks=[]
    def require(value,message):
        if not value:raise AssertionError(message)
    with tempfile.TemporaryDirectory(prefix='moews-fullmodel-controller-cpu-') as temporary:
        root=Path(temporary);stage=root/'candidate';gold=root/'gold'
        for st in (stage,gold):
            (st/'bin').mkdir(parents=True)
            for name in ('bench_moe_workspace_fullmodel','myds.metallib','myds'):(st/'bin'/name).write_bytes(b'CPU dummy never executed')
