#!/usr/bin/env python3
"""Check that the ledger's generated regions and expected.json match the raw rows,
and that the hard invariants held during the run.

Deliberately small. An earlier version had 169 checks; most of them compared numbers
in the ledger to numbers in a JSON file, i.e. they policed hand-transcription. The
fix is not a better policeman, it is to remove the transcription: the ledger tables
and expected.json are now generated by tools/gen_ledger_tables.py from raw/*.jsonl.
What remains here is only what a generator cannot produce:

  * invariants     — semantic conditions that make a run valid or void
  * freshness      — the committed tables equal what regeneration would produce
  * corpus         — the prompts on disk are the ones the manifest describes

Run `make audit-ledger`. Exit 1 on any failure. Needs no GPU and no model.
"""
import json
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BENCH = ROOT / "benchmarks" / "register_only_2026-10-27"
RAW = BENCH / "raw"
LEDGER = ROOT / "docs" / "2026-10-20-prefill-decode-pipeline-and-optimization-ledger.md"

fails = []


def check(name, ok, detail=""):
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + ("" if ok else f" — {detail}"))
    if not ok:
        fails.append(name)


def load(name):
    p = RAW / name
    if not p.exists():
        sys.exit(f"MISSING EVIDENCE: {p}\n"
                 f"Raw rows ship with this repository. If absent, the checkout is "
                 f"incomplete rather than the numbers wrong.")
    return [json.loads(l) for l in p.read_text().splitlines() if l.strip()]


def main():
    print("invariants")
    rig = load("rig.jsonl")
    runs = [r for r in rig if r.get("kind") == "run"]
    nonce = [r for r in runs if r.get("sample") == "nonce"]
    fixed = [r for r in runs if r.get("sample") == "fixed"]
    ends = [r for r in rig if r.get("kind") == "boot_end" and r.get("delta")]

    # 1. a cached row performed no prefill, so its t/s is not a measurement
    bad = [(r["arm"], r["boot"], r.get("cached")) for r in runs if r.get("cached") != 0]
    check("every timed row reported cached=0", not bad, str(bad))

    # 2. if both arms encoded the same number of chunks, the switch never took effect
    enc = {a: sorted({e["delta"]["encoded"] for e in ends if e["arm"] == a})
           for a in ("OFF", "ON")}
    check("the arms differ in encoded chunks (switch took effect)",
          enc["OFF"] == [0] and enc["ON"] and enc["ON"][0] > 0, str(enc))
    req = {a: sorted({e["delta"]["requests"] for e in ends if e["arm"] == a})
           for a in ("OFF", "ON")}
    check("both arms did identical work (same requests per boot)",
          req["OFF"] == req["ON"] and len(req["OFF"]) == 1, str(req))

    # 3. a fallback means the candidate declined, i.e. the reference path was measured
    fb = [(e["arm"], e["delta"]["fallbacks"], e["delta"]["failures"]) for e in ends
          if e["delta"]["fallbacks"] or e["delta"]["failures"]]
    check("no fallbacks and no failures", not fb, str(fb))

    # 4. equivalence: same prompt, both arms, byte-identical output
    shas = {a: sorted({r["sha"] for r in fixed if r["arm"] == a}) for a in ("OFF", "ON")}
    check("both arms produced identical bytes on the fixed prompt",
          shas["OFF"] == shas["ON"] and len(shas["OFF"]) == 1, str(shas))

    # 5. the two arms must not be distinguishable by the amount of work, only by speed
    med = {a: st.median([r["tps"] for r in nonce if r["arm"] == a]) for a in ("OFF", "ON")}
    check("the ON arm is faster, and by a margin far above its spread",
          med["ON"] > med["OFF"] and
          (med["ON"] - med["OFF"]) > 5 * max(
              st.stdev([r["tps"] for r in nonce if r["arm"] == a]) for a in ("OFF", "ON")),
          f"OFF {med['OFF']:.1f} vs ON {med['ON']:.1f}")

    # the same invariants must hold on the independent rerun by the shipped harness
    repro = RAW / "reproduce_run.jsonl"
    if repro.exists():
        rr = [json.loads(l) for l in repro.read_text().splitlines() if l.strip()]
        r_runs = [r for r in rr if r.get("kind") == "run"]
        r_fixed = [r for r in r_runs if r.get("sample") == "fixed"]
        r_ends = [r for r in rr if r.get("kind") == "boot_end" and r.get("delta")]
        check("rerun: every timed row reported cached=0",
              all(r.get("cached") == 0 for r in r_runs),
              str([(r["arm"], r["boot"], r.get("cached")) for r in r_runs if r.get("cached") != 0]))
        r_enc = {a: sorted({e["delta"]["encoded"] for e in r_ends if e["arm"] == a})
                 for a in ("OFF", "ON")}
        check("rerun: arms differ in encoded chunks", r_enc["OFF"] == [0] and r_enc["ON"] and
              r_enc["ON"][0] > 0, str(r_enc))
        r_fb = [(e["arm"], e["delta"]["fallbacks"], e["delta"]["failures"]) for e in r_ends
                if e["delta"]["fallbacks"] or e["delta"]["failures"]]
        check("rerun: no fallbacks and no failures", not r_fb, str(r_fb))
        r_sha = {a: sorted({r["sha"] for r in r_fixed if r["arm"] == a}) for a in ("OFF", "ON")}
        check("rerun: both arms produced identical bytes", r_sha["OFF"] == r_sha["ON"] and
              len(r_sha["OFF"]) == 1, str(r_sha))

    print("\nfreshness (tables are generated, not transcribed)")
    sys.path.insert(0, str(ROOT / "tools"))
    import gen_ledger_tables as gen  # noqa: E402

    ab, sw, dec, g = gen.ab_facts(), gen.sweep_facts(), gen.dec_facts(), gen.gpu_facts()
    want = gen.apply(LEDGER.read_text(), gen.regions(ab, sw, dec, g))
    check("ledger generated regions are current", LEDGER.read_text() == want,
          "run: python3 tools/gen_ledger_tables.py --write")
    exp_want = json.dumps(gen.build_expected(ab, sw, dec, g, gen.smoke_facts()),
                          ensure_ascii=False, indent=2) + "\n"
    check("expected.json is current", (BENCH / "expected.json").read_text() == exp_want,
          "run: python3 tools/gen_ledger_tables.py --write")

    print("\ncorpus")
    man = json.loads((BENCH / "prompts" / "manifest.json").read_text())
    drift = [n for n, m in man.items()
             if not (BENCH / "prompts" / n).exists() or
             (BENCH / "prompts" / n).stat().st_size != m["bytes"]]
    check("every manifest entry matches a file of the recorded size", not drift, str(drift[:5]))
    check("no extra prompt files beyond the manifest",
          sorted(man) == sorted(p.name for p in (BENCH / "prompts").glob("*.txt")),
          "manifest and directory disagree; run make corpus-check")

    total = len(fails)
    print(f"\n{total} failure(s)")
    if fails:
        print("VERDICT: FAIL")
        return 1
    print("VERDICT: PASS — invariants held, tables are current, corpus is intact")
    return 0


if __name__ == "__main__":
    sys.exit(main())
