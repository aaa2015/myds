#!/usr/bin/env python3
"""Generate/check the lossless signed4 dictionary embedded in the IQ2 shader.

Default: print the generated block.  --check validates the checked-in block
and exhaustively compares all 256 grid x 128 parity-sign combinations.
"""

import argparse
from pathlib import Path
import re
import sys


BEGIN = "// BEGIN GENERATED IQ2 SIGNED4 TABLES"
END = "// END GENERATED IQ2 SIGNED4 TABLES"


def generate(source):
    match = re.search(
        r"static constant ulong myds_iq2_v41_grid\[256\] = \{(.*?)\};",
        source,
        re.S,
    )
    if match is None:
        raise ValueError("the authoritative 256-entry IQ2 grid was not found")
    grid = [int(x, 16).to_bytes(8, "little")
            for x in re.findall(r"0x([0-9a-fA-F]+)", match.group(1))]
    if len(grid) != 256 or {v for row in grid for v in row} != {8, 25, 43}:
        raise ValueError("the authoritative IQ2 grid shape or magnitudes changed")
    patterns = sorted({row[j:j + 4] for row in grid for j in (0, 4)})
    if len(patterns) != 74:
        raise ValueError("the signed4 dictionary is no longer 74 entries")
    index = {pattern: i for i, pattern in enumerate(patterns)}
    mapping = [index[row[:4]] | (index[row[4:]] << 7) for row in grid]
    values = [tuple(-v if sign & (1 << j) else v
                    for j, v in enumerate(pattern))
              for pattern in patterns for sign in range(16)]
    cases = 0
    for row, packed in zip(grid, mapping):
        for s7 in range(128):
            sign = s7 | ((s7.bit_count() & 1) << 7)
            actual = (values[(packed & 127) * 16 + (sign & 15)]
                      + values[(packed >> 7) * 16 + (sign >> 4)])
            expected = tuple(-v if sign & (1 << j) else v
                             for j, v in enumerate(row))
            if actual != expected:
                raise ValueError("signed4 reconstruction differs from the original grid")
            cases += 1

    lines = [BEGIN,
             "// Generated by tools/gen_iq2_signed4_tables.py; do not hand-edit.",
             "// 256 ushort mappings + 74 * 16 char4 values = 5248 bytes.",
             "static constant ushort myds_iq2_v41_signed4_map[256] = {"]
    for start in range(0, len(mapping), 16):
        lines.append("    " + ", ".join(str(x) for x in mapping[start:start + 16]) + ",")
    lines.extend(["};", "", "static constant char4 myds_iq2_v41_signed4_values[1184] = {"])
    for start in range(0, len(values), 4):
        lines.append("    " + ", ".join(
            "char4(" + ", ".join(str(x) for x in row) + ")"
            for row in values[start:start + 4]) + ",")
    lines.extend(["};", END])
    return "\n".join(lines), cases


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--source", type=Path,
                        default=Path(__file__).resolve().parents[1] / "metal/myds_iq2_v41.metal")
    args = parser.parse_args()
    source = args.source.read_text()
    try:
        block, cases = generate(source)
        if args.check:
            start = source.find(BEGIN)
            end = source.find(END, start)
            if start < 0 or end < 0 or source[start:end + len(END)] != block:
                raise ValueError("embedded signed4 table block is missing or stale")
            print(f"signed4 tables: PASS cases={cases} signed_values={cases * 8} "
                  "patterns=74 table_bytes=4736 mapping_bytes=512 threadgroup_bytes=5248")
        else:
            print(block)
    except ValueError as error:
        print(f"signed4 tables: FAIL: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
