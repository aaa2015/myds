#!/usr/bin/env python3
"""Build an isolated, default-off gathered-prefill output-register probe.

No production runtime or shader registry is changed.  The native head-first
NE=NSG=NWG=1 template is the oracle.  Only the per-lane output accumulator is
moved from threadgroup storage to four private float4 values. Q, score, PV,
32-key online-softmax and sink expressions keep the native order.  An explicit
contract(off) scope on output addition retains the rounding boundary that the
native threadgroup store imposed between scaling and adding each block.

Compilation alone is not a numerical or performance result. The companion
bench_prefill_output_register.m requires complete output bit comparisons first.
"""
import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import sys

sys.dont_write_bytecode = True
SYMBOL = "kernel_myds_prefill_output_register_f16_dk512_dv512"
TYPES = ("half4, half4, half4, float, float, float4, float4, "
         "half4, 1, dequantize_f16_t4, half4, 1, dequantize_f16_t4, "
         "512, 512, 1, 1, 32, true")


def sha(data):
    return hashlib.sha256(data).hexdigest()


def native_template(source):
    at = source.index("kernel void kernel_flash_attn_ext_vec(")
    start = source.rfind("template<", 0, at)
    opening = source.index("{", at)
    depth, end = 1, opening + 1
    while depth:
        depth += (source[end] == "{") - (source[end] == "}")
        end += 1
    return source[start:end]


def generate(source):
    native = native_template(source)
    edits = [
        ("kernel void kernel_flash_attn_ext_vec(",
         "kernel void probe_prefill_output_register("),
        ("    static_assert(DK % 32 == 0, \"DK must be divisible by 32\");",
         """    static_assert(DK == 512 && DV == 512 && NE == 1 && C == 32 && HEAD_FIRST,
                  "narrow gathered prefill output-register probe");
    if (FC_flash_attn_ext_vec_nsg != 1 || FC_flash_attn_ext_vec_nwg != 1 ||
        !FC_flash_attn_ext_vec_has_mask || !FC_flash_attn_ext_vec_has_sinks ||
        FC_flash_attn_ext_vec_has_bias || FC_flash_attn_ext_vec_has_scap ||
        FC_flash_attn_ext_vec_has_kvpad || FC_flash_attn_ext_vec_shared_kvpad ||
        FC_flash_attn_ext_vec_ns10 != 512 || FC_flash_attn_ext_vec_ns20 != 512 ||
        args.ne11 != 640 || args.ne02 != 64 || args.ne03 != 1 ||
        args.ne_12_2 != 1 || args.ne_12_3 != 1 || args.nb_kvq != 655360 ||
        args.ne32 != 1 || args.ne33 != 1) return;
    float4 output_acc[4];
    static_assert(DK % 32 == 0, "DK must be divisible by 32");"""),
        ("        so4[i*NL] = (o4_t) 0.0f;",
         "        output_acc[i] = (o4_t) 0.0f;"),
        ("\n                        so4[ii*NL] *= ms;",
         "\n                        output_acc[ii] *= ms;"),
        ("                        so4[ii*NL] += lo[ii];",
         """                        {
                            #pragma clang fp contract(off)
                            output_acc[ii] += lo[ii];
                        }"""),
        ("\n                    so4[ii*NL] *= ms;",
         "\n                    output_acc[ii] *= ms;"),
        ("            dst4[rid*DV4*NWG + NWG*i + iwg] = (float4) so4[i]*S;",
         "            dst4[rid*DV4*NWG + NWG*i + iwg] = (float4) output_acc[i/NW]*S;"),
    ]
    body = native
    for old, new in edits:
        if body.count(old) != 1:
            raise ValueError("Expected one native anchor: " + repr(old))
        body = body.replace(old, new, 1)
    restored = body
    for old, new in reversed(edits):
        if restored.count(new) != 1:
            raise ValueError("Expected one reverse anchor")
        restored = restored.replace(new, old, 1)
    if restored != native:
        raise ValueError("Transformation touched unlisted native expressions")
    generated = """// Isolated gathered-prefill output-register probe. Generated by
// tools/build_prefill_output_register_probe.py. Not in production shader lists.
// Keep the native Q/score/PV code and original 3328-byte allocation for this
// first ablation; only four output float4 accumulators become lane-private.
// Contract(off) on block output addition preserves the scale/add boundary.

""" + body + f"""

typedef decltype(probe_prefill_output_register<{TYPES}>) prefill_output_register_t;
template [[host_name("{SYMBOL}")]]
kernel prefill_output_register_t probe_prefill_output_register<{TYPES}>;
"""
    return generated, dict(native_template_sha256=sha(native.encode()),
                          exact_edits=[dict(before=a, after=b) for a, b in edits],
                          reverse_edits_restore_native_byte_for_byte=True)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--source-root", type=Path, required=True)
    p.add_argument("--out-dir", type=Path, required=True)
    p.add_argument("--emit-only", action="store_true")
    a = p.parse_args()
    root = a.source_root.resolve(strict=True)
    out = a.out_dir.resolve()
    if out.exists() or out.is_relative_to(root):
        raise ValueError("A new output directory outside the checkout is required")
    source = (root / "metal/flash_attn.metal").read_text()
    generated, proof = generate(source)
    if (root / "metal/myds_prefill_output_register.metal").read_text() != generated:
        raise ValueError("Checked-in probe differs from the exact transformation")
    out.mkdir(parents=True)
    (out / "probe.metal").write_text(generated)
    spec = importlib.util.spec_from_file_location("build", root / "tools/build_metallib.py")
    build = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(build)
    (out / "all.metal").write_text(build.PREAMBLE + '\n#line 1 "flash_attn.metal"\n' +
                                   source + '\n#line 1 "probe.metal"\n' + generated)
    identity = dict(schema_version=1, symbol=SYMBOL, source_root=str(root),
                    native_flash_sha256=sha(source.encode()), probe_sha256=sha(generated.encode()),
                    builder_sha256=sha(Path(__file__).read_bytes()), proof=proof,
                    production_registered=False, gpu_work_submitted=False,
                    compile_only_pass=False)
    if not a.emit_only:
        commands = [
            ["xcrun", "-sdk", "macosx", "metal", "-mmacosx-version-min=26.0", "-O3",
             "-ffast-math", "-DDS4_METAL_HC_STABLE=1", "-DDS4_METAL_NORM_RSQRT_DISABLE=1",
             "-c", str(out / "all.metal"), "-o", str(out / "probe.air")],
            ["xcrun", "-sdk", "macosx", "metallib", str(out / "probe.air"),
             "-o", str(out / "probe.metallib")],
        ]
        env = dict(os.environ)
        env.setdefault("DEVELOPER_DIR", "/Applications/Xcode.app/Contents/Developer")
        with (out / "compile.log").open("w") as log:
            for command in commands:
                log.write(json.dumps(command) + "\n")
                log.flush()
                subprocess.run(command, env=env, stdout=log, stderr=log, check=True)
        identity.update(compile_only_pass=True, commands=commands,
                        metallib_sha256=sha((out / "probe.metallib").read_bytes()))
    (out / "source-identity.json").write_text(json.dumps(identity, indent=2) + "\n")
    print(json.dumps(identity, indent=2))


if __name__ == "__main__":
    main()
