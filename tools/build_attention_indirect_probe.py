#!/usr/bin/env python3
"""Compile a single-head, row-ID F16 layout probe without production changes.

The native template is copied from a SHA-pinned flash_attn.metal. Only its
name, extra buffer8, K/V byte offsets and direct-load addresses change. Reversing
those exact edits must recover the complete original template byte-for-byte.
The checked-in probe shader must equal the generated source. No runtime shader
list is modified. This tool compiles AIR/metallib only and submits no GPU work.

The CPU dictionary/IDs from the real capture test a source-layout hypothesis;
they do not implement a production GPU layout builder or prove end-to-end gain.
"""
import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import sys

sys.dont_write_bytecode=True
FLASH_SHA256='503fc1ec7fb94130f4e44c1a1147bf182d11c9993cc0688e8ed2f4993df7bdc6'
SYMBOL='kernel_myds_prefill_attention_indirect_f16_dk512_dv512'
TYPES=('half4, half4, half4, float, float, float4, float4, '
       'half4, 1, dequantize_f16_t4, half4, 1, dequantize_f16_t4, 512, 512, 1, 1, 32, true')


def require(value,message):
    if not value:raise ValueError(message)


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def template(source):
    at=source.index('kernel void kernel_flash_attn_ext_vec(')
    start=source.rfind('template<',0,at)
    opening=source.index('{',at);depth=1;end=opening+1
    while depth:
        if source[end]=='{':depth+=1
        elif source[end]=='}':depth-=1
        end+=1
    return source[start:end]


def generate(flash):
    native=template(flash)
    edits=[
      ('kernel void kernel_flash_attn_ext_vec(', 'kernel void probe_myds_flash_attn_ext_vec_indirect('),
      ('        device       char * dst,',
       '        device       char * dst,\n        device const uint32_t * row_ids [[buffer(8)]],'),
      ('''        /* B 方案：紧凑 slab 下每个 query 的键从自己的 [0,640) 段取。
         * nb_kvq==0 时整句为恒等变换，与旧行为逐位一致。 */
        if (args.nb_kvq != 0) {
            k += (ulong)iq1 * args.nb_kvq;
            v += (ulong)iq1 * args.nb_kvq;
        }''',
       '        // Indirect source is query-independent; row_ids selects each logical key.'),
      ('(device const k4_t *) (k + ic*args.nb11)', '(device const k4_t *) (k)'),
      ('pk4[cc*NE*NS10/4 +  ii*NL]',
       'pk4[(ulong)row_ids[(ulong)iq1*640u + (uint)(ic + cc)]*(NS10/4) +  ii*NL]'),
      ('(device const v4_t *) (v + ic*args.nb21)', '(device const v4_t *) (v)'),
      ('pv4[cc*NE*NS20/4 + ii*NL]',
       'pv4[(ulong)row_ids[(ulong)iq1*640u + (uint)(ic + cc)]*(NS20/4) + ii*NL]'),
    ]
    body=native
    for old,new in edits:
        require(body.count(old)==1,'Native edit anchor must be unique: '+old[:90])
        body=body.replace(old,new,1)
    restored=body
    for old,new in reversed(edits):
        require(restored.count(new)==1,'Reverse edit anchor must be unique')
        restored=restored.replace(new,old,1)
    require(restored==native,'Unexpected arithmetic/control-flow modification')
    header='''// Generated by tools/build_attention_indirect_probe.py; diagnostic layout probe.
// Append after the unchanged flash_attn.metal; never registered for production.
// Original native template math, 32-key blocks, PV loop, reductions and 3328B
// scratch remain intact. One head per TG, groups=(64,rows,1), threads=(32,1,1).
// ABI: original args200 and buffers0..7; buffer8 is uint32 row_ids[rows*640].
// Buffers2/3 bind the same canonical F16 source of source_rows*512 elements.
// Host must validate every row ID < source_rows before command creation, full
// source/map ranges and nonaliasing outputs. Retain original mask and args.
// Supported specialization only: DK=DV512, NE=NSG=NWG1, 64 heads, 640 keys,
// ns10=ns20=512, cache groups1, mask+sinks true, bias/scap/pad false, head-first.
// The unchanged generic pad/quantized branches are outside this probe contract.
// This exact CPU dictionary is a component input, not a production GPU builder.
// A win still requires production source preparation including its measured cost.

'''
    wrapper=f'''

typedef decltype(probe_myds_flash_attn_ext_vec_indirect<{TYPES}>) myds_prefill_attention_indirect_t;
template [[host_name("{SYMBOL}")]]
kernel myds_prefill_attention_indirect_t probe_myds_flash_attn_ext_vec_indirect<{TYPES}>;
'''
    return header+body+wrapper,dict(native_template_sha256=hashlib.sha256(native.encode()).hexdigest(),
        transformed_template_sha256=hashlib.sha256(body.encode()).hexdigest(),
        reverse_edits_restore_native_byte_for_byte=True,
        exact_edits=[dict(before=old,after=new) for old,new in edits])


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-root',type=Path,required=True)
    parser.add_argument('--out-dir',type=Path,required=True)
    parser.add_argument('--emit-only',action='store_true')
    args=parser.parse_args()
    root=args.source_root.resolve(strict=True);out=args.out_dir.resolve()
    require(not out.exists() and not out.is_relative_to(root),'New private output outside source checkout required')
    original=root/'metal/flash_attn.metal'
    require(sha(original)==FLASH_SHA256,'Native flash_attn source differs from pinned reviewed version')
    generated,proof=generate(original.read_text())
    checked_in=root/'metal/myds_prefill_attention_indirect.metal'
    require(checked_in.is_file() and checked_in.read_text()==generated,'Checked-in indirect probe differs from generator')
    out.mkdir(parents=True)
    (out/'probe.metal').write_text(generated)
    spec=importlib.util.spec_from_file_location('frozen_build',root/'tools/build_metallib.py')
    build=importlib.util.module_from_spec(spec);spec.loader.exec_module(build)
    combined=build.PREAMBLE+'\n#line 1 "flash_attn.metal"\n'+original.read_text()+\
        '\n#line 1 "myds_prefill_attention_indirect.metal"\n'+generated
    (out/'all.metal').write_text(combined)
    identity=dict(schema_version=1,gpu_work_submitted=False,production_registered=False,
        source_root=str(root),native_flash_sha256=FLASH_SHA256,probe_sha256=sha(checked_in),
        builder_sha256=sha(Path(__file__)),symbol=SYMBOL,proof=proof,
        abi=dict(args_bytes=200,buffer_indices=dict(args=0,q_f32=1,k_f16_source=2,v_same_f16_source=3,
            original_mask_f16=4,sinks_f32=5,unused_pad=6,out_f32=7,row_ids_u32=8),
            groups=[64,'rows',1],threads=[32,1,1],dynamic_threadgroup_bytes=3328,
            function_constants={str(i):v for i,v in zip((400,401,402,403,404,405,420,421,422,423),
                (True,True,False,False,False,False,512,512,1,1))}),
        limitations=['No GPU parity or performance has been measured for this indirect probe.',
            'Input CPU dictionary is not a production source-building contract.',
            'Identical source arithmetic does not prove identical device fast-math contraction.'])
    if not args.emit_only:
        commands=[['xcrun','-sdk','macosx','metal','-mmacosx-version-min=26.0','-O3','-ffast-math',
            '-DDS4_METAL_HC_STABLE=1','-DDS4_METAL_NORM_RSQRT_DISABLE=1','-c',str(out/'all.metal'),'-o',str(out/'probe.air')],
            ['xcrun','-sdk','macosx','metallib',str(out/'probe.air'),'-o',str(out/'probe.metallib')]]
        env=dict(os.environ);env.setdefault('DEVELOPER_DIR','/Applications/Xcode.app/Contents/Developer')
        with (out/'compile.log').open('w') as log:
            for command in commands:
                log.write(json.dumps(command)+'\n');log.flush()
                subprocess.run(command,env=env,stdout=log,stderr=log,check=True)
        identity.update(compile_only_pass=True,commands=commands,metallib_sha256=sha(out/'probe.metallib'))
    (out/'source-identity.json').write_text(json.dumps(identity,indent=2)+'\n')
    print(json.dumps({k:identity[k] for k in ('symbol','native_flash_sha256','probe_sha256','gpu_work_submitted')},indent=2))


if __name__=='__main__':main()
